const assert = require('node:assert/strict');
const { createSteamFriends } = require('../src/steam-friends.cjs');
const owner = '76561198000000000', friend = '76561198000000001', stranger = '76561198000000002';
let members = [{ steamid: friend, relationship: 'friend' }], players = [], failList = false, failPresence = false, calls = [], time = 1000;
const service = createSteamFriends({ now: () => time, request: async url => {
  calls.push(url);
  const list = url.pathname.includes('GetFriendList');
  return { ok: !(list ? failList : failPresence), status: 403, json: async () => list
    ? { friendslist: { friends: members } } : { response: { players: players.filter(player => url.searchParams.get('steamids').split(',').includes(player.steamid) || player.steamid === stranger) } } };
} });
const get = (extra = {}) => service.list({ steamId: owner, apiKey: 'test-key', force: true, ...extra });
(async () => {
  players = [friend, stranger].map(steamid => ({ steamid, personaname: steamid === friend ? 'Actual friend' : 'Not a friend', personastate: 1, gameid: '570', gameextrainfo: 'Dota 2' }));
  let data = await get();
  assert.deepEqual(data.friends.map(f => f.id), [friend], 'summaries cannot introduce strangers');
  assert.equal(data.friends[0].gameId, '570');
  members = [];
  assert.deepEqual((await get()).friends, [], 'empty verified list stays empty');
  members = [{ steamid: stranger, relationship: 'blocked' }, { steamid: owner, relationship: 'friend' }, { steamid: friend, relationship: 'friend' }, { steamid: friend, relationship: 'friend' }];
  assert.deepEqual((await get()).friends.map(f => f.id), [friend], 'exclude blocked, self and duplicates');
  failList = true;
  data = await get();
  assert.equal(data.status, 'unavailable');
  assert.deepEqual(data.friends, [], 'failed membership request never reuses stale people');
  failList = false;
  failPresence = true;
  data = await get();
  assert.equal(data.status, 'partial');
  assert.equal(data.friends[0].gameId, '', 'failed summaries clear activity');
  failPresence = false;
  players[0].personastate = 0;
  assert.equal((await get()).friends[0].game, '', 'offline stale game fields do not mean currently playing');
  players[0].personastate = 1;
  delete players[0].gameid;
  assert.equal((await get()).friends[0].game, '', 'a title alone is not live presence');
  const before = calls.length;
  await get({ force: false });
  assert.equal(calls.length, before, 'same account uses short cache');
  await get({ force: false, steamId: stranger });
  assert.ok(calls.length > before, 'switching accounts cannot reuse the previous list');
  const keyBefore = calls.length;
  await get({ force: false, apiKey: 'changed-key', steamId: stranger });
  assert.ok(calls.length > keyBefore, 'credentials change invalidates cache');
  assert.equal((await get({ apiKey: '' })).status, 'needs-api-key');
  assert.equal((await get({ steamId: '' })).status, 'no-account');
  members = Array.from({ length: 305 }, (_, i) => ({ steamid: String(BigInt(owner) + 10n + BigInt(i)), relationship: 'friend' }));
  players = members.map(m => ({ steamid: m.steamid, personaname: m.steamid, personastate: 1 }));
  data = await get();
  assert.equal(data.friends.length, 305, 'large friends lists are not truncated');
  assert.ok(calls.filter(u => u.pathname.includes('GetPlayerSummaries')).every(u => u.searchParams.get('steamids').split(',').length <= 100));
  time += 21000;
  members = [];
  assert.equal((await get({ force: false })).friends.length, 0, 'removed friends disappear on next refresh');
  console.log('PASS: verified membership, empty/private lists, stale presence, account/key changes, cache expiry and 305-friend batching.');
})().catch(error => { console.error(error); process.exitCode = 1; });
