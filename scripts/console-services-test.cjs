const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { createConsoleServices, mapProduct } = require('../src/console-services.cjs');
(async()=>{
  const directory=await fs.mkdtemp(path.join(os.tmpdir(),'xbox-console-services-'));
  const product={ProductId:'9NKX70BBCDRN',ProductKind:'Game',LocalizedProperties:[{ProductTitle:'Review game',ProductDescription:'<p>Real description field</p>',Images:[{ImagePurpose:'BoxArt',Width:600,Height:600,Uri:'//store-images.s-microsoft.com/image/review'},{ImagePurpose:'Screenshot',Width:1920,Height:1080,Uri:'https://example.com/untrusted'}]}],Properties:{Attributes:[{Name:'SinglePlayer'}]}};
  let requests=0;
  const mock=async url=>{requests++;return {ok:true,json:async()=>url.includes('sigls')?[{title:'All PC Games'},{id:product.ProductId}]:{Products:[product]}};};
  const service=createConsoleServices(directory,mock);
  const [first,second]=await Promise.all([service.getGamePassCatalog(),service.getGamePassCatalog()]);
  assert.equal(requests,2,'Concurrent catalog requests should share the fetch');
  assert.equal(first[0].title,second[0].title);
  assert.equal(first[0].artwork.tileIsSquare,true);
  assert.deepEqual(first[0].details.screenshots,[],'Untrusted image hosts should be excluded');
  assert.deepEqual(first[0].details.categories,['Single player']);
  assert.equal(mapProduct(product).details.description,'Real description field');
  const offline=createConsoleServices(directory,async()=>{throw Error('offline');});
  assert.equal((await offline.getGamePassCatalog())[0].title,'Review game');
  assert.equal((await offline.getCatalogDetails(product.ProductId)).title,'Review game');
  await assert.rejects(()=>offline.getCatalogDetails('../settings'),'Invalid catalog identity must fail');
  const listing=await service.browseFiles(path.resolve(__dirname,'../build'),'image');
  assert(listing.entries.some(item=>item.name==='icon.png'));
  assert(!listing.entries.some(item=>item.name==='icon.svg'));
  assert((await service.readGamerpic(path.resolve(__dirname,'../build/icon.png'))).startsWith('data:image/png;base64,'));
  await assert.rejects(()=>service.browseFiles('relative/path','game'));
  await assert.rejects(()=>service.readGamerpic(path.resolve(__dirname,'../package.json')));
  console.log('PASS: catalog mapping, shared requests, offline cache, image allowlist, and file-picker validation');
})().catch(error=>{console.error(error);process.exitCode=1;});
