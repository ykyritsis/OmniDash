const assert=require('node:assert/strict');
const {calculate,level}=require('../src/pc-gamerscore.cjs');
const catalog=[{apiname:'common',achieved:1},{apiname:'rare',achieved:0},{apiname:'secret',achieved:0}];
const rarity=new Map([['common',90],['rare',1],['secret',10]]);
const partial=calculate(catalog,rarity);
assert.equal(Object.values(partial.pointTable).reduce((n,a)=>n+a.points,0),1000);
assert.ok(partial.pointTable.rare.points>partial.pointTable.common.points);
assert.equal(partial.points,partial.pointTable.common.points);
assert.equal(calculate(catalog.map(a=>({...a,achieved:1})),rarity).points,1000);
assert.equal(calculate(catalog.map(a=>({...a,achieved:0})),rarity).points,0);
assert.deepEqual(calculate([...catalog].reverse(),rarity).pointTable,partial.pointTable);
assert.deepEqual(calculate(catalog,new Map([['common',1]]),partial.pointTable).pointTable,partial.pointTable);
assert.equal(calculate([...catalog,catalog[0]],rarity).points,partial.points);
assert.equal(calculate([]).possible,0);
const unknown=calculate([{apiname:'a',achieved:1},{apiname:'b',achieved:0}]);assert.equal(unknown.points,500);
const expanded=calculate([...catalog,{apiname:'new',achieved:1}],rarity,partial.pointTable);assert.equal(Object.values(expanded.pointTable).reduce((n,a)=>n+a.points,0),1000);
const huge=calculate(Array.from({length:20000},(_,i)=>({apiname:String(i),achieved:1})));assert.equal(huge.points,1000);assert.equal(huge.total,20000);
assert.equal(level(0),1);assert.equal(level(4000),3);
console.log('PASS 1,000-point budgets, rarity, deterministic allocation, stable resyncs, complete/partial/empty catalogs and duplicate protection');
